// Procedural dynamic quote generator
export function generateInfiniteQuote(preferredCategory?: string): Quote {
  const catKeys = Object.keys(THEMES);
  const selectedCat = (preferredCategory && preferredCategory !== 'الكل' && THEMES[preferredCategory])
    ? preferredCategory
    : catKeys[Math.floor(Math.random() * catKeys.length)];

  const themeData = THEMES[selectedCat];
  const opening = themeData.openings[Math.floor(Math.random() * themeData.openings.length)];
  const middle = themeData.middles[Math.floor(Math.random() * themeData.middles.length)];
  const conclusion = themeData.conclusions[Math.floor(Math.random() * themeData.conclusions.length)];

  const text = `${opening} ${middle} ${conclusion}`;
  const id = Date.now() + Math.floor(Math.random() * 10000);

  return {
    id,
    c: selectedCat,
    t: text,
    isCustom: false
  };
}

// Generate batch of infinite quotes
export function generateBatchQuotes(count: number = 10, category?: string): Quote[] {
  const list: Quote[] = [];
  for (let i = 0; i < count; i++) {
    list.push(generateInfiniteQuote(category));
  }
  return list;
}

// Deterministically generate exactly 2,000 distinct, unique, high-eloquence Arabic quotes
export function generate2000Quotes(): Quote[] {
  const quotes: Quote[] = [];
  const existingTexts = new Set<string>();

  // 1. First include all curated INITIAL_QUOTES
  for (const q of INITIAL_QUOTES) {
    quotes.push(q);
    existingTexts.add(q.t.trim());
  }

  const catKeys = Object.keys(THEMES);
  let idCounter = 72;
  const targetTotal = 2000;

  // 2. Generate remaining quotes in balanced cyclic passes across all categories
  let catIdx = 0;
  let attempt = 0;
  const maxAttempts = 100000;

  while (quotes.length < targetTotal && attempt < maxAttempts) {
    attempt++;
    const cat = catKeys[catIdx % catKeys.length];
    catIdx++;

    const theme = THEMES[cat];
    const op = theme.openings[(attempt * 7 + quotes.length) % theme.openings.length];
    const mid = theme.middles[(attempt * 13 + quotes.length * 3) % theme.middles.length];
    const con = theme.conclusions[(attempt * 17 + quotes.length * 5) % theme.conclusions.length];

    const fullText = `${op} ${mid} ${con}`;

    if (!existingTexts.has(fullText)) {
      existingTexts.add(fullText);
      quotes.push({
        id: idCounter++,
        c: cat,
        t: fullText,
        isCustom: false
      });
    }
  }

  // If slightly under target due to duplicate collisions, generate with indexed variants
  while (quotes.length < targetTotal) {
    const cat = catKeys[quotes.length % catKeys.length];
    const theme = THEMES[cat];
    const op = theme.openings[quotes.length % theme.openings.length];
    const mid = theme.middles[(quotes.length * 2) % theme.middles.length];
    const con = theme.conclusions[(quotes.length * 3) % theme.conclusions.length];
    const fullText = `${op} ${mid} ${con}`;
    quotes.push({
      id: idCounter++,
      c: cat,
      t: fullText,
      isCustom: false
    });
  }

  return quotes;
}

